function methodUsage(methodId) {
  const cases = [];
  const branchCounts = {};
  let questionCount = 0;
  for (const c of CASES) {
    let count = 0;
    for (const q of c.bank) {
      if (q.method === methodId) count++;
    }
    if (!count) continue;
    questionCount += count;
    branchCounts[c.branch] = (branchCounts[c.branch] || 0) + count;
    cases.push({ caseId: c.id, count, branch: c.branch });
  }
  cases.sort((a, b) => b.count - a.count);
  const topBranch = Object.entries(branchCounts).sort((a, b) => b[1] - a[1])[0]?.[0] || null;
  return {
    branch: topBranch,
    questionCount,
    relatedCaseIds: cases.slice(0, 3).map((x) => x.caseId),
  };
}

function buildMethodEntry(methodId, method) {
  const usage = methodUsage(methodId);
  return {
    id: `method:${methodId}`,
    term: method.title,
    aliases: Array.from(
      new Set([
        methodId,
        methodId.replace(/_/g, " "),
        ...(METHOD_ALIASES[methodId] || []),
      ])
    ),
    kind: "method",
    branch: usage.branch || "foundations",
    featured: usage.questionCount >= 30,
    oneLine: truncate(firstSentence(method.intuition), 150),
    plainEnglish: method.intuition,
    whenToUse: method.assumptions?.[0]
      ? `Use it when the scientific question fits and this key assumption is plausible: ${method.assumptions[0]}`
      : "Use it when the scientific question maps to the method and its assumptions are reasonable.",
    commonMistake: method.pitfalls?.[0] || "Using the method without checking whether its assumptions match the study design and data.",
    example: usage.relatedCaseIds[0]
      ? `Practice it in ${CASES.find((c) => c.id === usage.relatedCaseIds[0])?.title || "a related case"}.`
      : "",
    assumptions: method.assumptions || [],
    pitfalls: method.pitfalls || [],
    reading: method.reading || [],
    relatedTerms: METHOD_RELATED_TERMS[methodId] || [],
    relatedMethods: [],
    relatedCaseIds: usage.relatedCaseIds,
    methodId,
    questionCount: usage.questionCount,
  };
}


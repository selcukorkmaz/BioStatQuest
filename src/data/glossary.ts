function normalizeGlossaryText(value = "") {
  return String(value)
    .replaceAll("α", " alpha ")
    .replaceAll("β", " beta ")
    .replaceAll("²", " 2 ")
    .replaceAll("–", " ")
    .replaceAll("—", " ")
    .replaceAll("/", " ")
    .replaceAll("_", " ")
    .normalize("NFKD")
    .replace(/[\u0300-\u036f]/g, "")
    .toLowerCase()
    .replace(/[^a-z0-9\s]+/g, " ")
    .replace(/\s+/g, " ")
    .trim();
}

function firstSentence(text = "") {
  const match = String(text).trim().match(/^(.+?[.!?])(?:\s|$)/);
  return match ? match[1].trim() : String(text).trim();
}

function truncate(text = "", max = 165) {
  if (text.length <= max) return text;
  return text.slice(0, max - 1).trimEnd() + "…";
}

